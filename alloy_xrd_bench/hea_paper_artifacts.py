"""Generate HEA v1.1 paper tables and figures from frozen evaluation artifacts."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Sequence

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


MODEL_ORDER = [
    "composition-ridge",
    "peak-xgboost",
    "resnet1d",
    "transformer",
    "physics-transformer",
]
MODEL_LABEL = {
    "composition-ridge": "Composition Ridge",
    "peak-xgboost": "Peak XGBoost",
    "resnet1d": "ResNet1D",
    "transformer": "Spectrum Transformer",
    "physics-transformer": "Physics-Constrained Transformer",
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate_paper_artifacts(
    summary_path: Path,
    calibrated_pairs_path: Path,
    perturbation_root: Path,
    output: Path,
) -> dict[str, str]:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    for split, models in summary["split_model_aggregates"].items():
        for model in MODEL_ORDER:
            if model not in models:
                continue
            value = models[model]
            rows.append({
                "split_column": split,
                "model": model,
                "seed_count": int(value["seed_count"]),
                "parent_macro_mae_mean": float(value["sro_parent_macro_mae_mean"]),
                "random_seed_std": float(value["sro_parent_macro_mae_std"]),
            })
    results = pd.DataFrame(rows)
    results_csv = output / "hea_sro_results.csv"
    results.to_csv(results_csv, index=False)
    tex_lines = [
        "% Generated by alloy_xrd_bench.hea_paper_artifacts; do not edit.",
        "\\begin{tabular}{llrr}",
        "\\toprule",
        "Split & Model & MAE $\\downarrow$ & Seed SD \\\\",
        "\\midrule",
    ]
    for row in rows:
        split = row["split_column"].replace("_", "\\_")
        tex_lines.append(
            f"{split} & {MODEL_LABEL.get(row['model'], row['model'])} & "
            f"{row['parent_macro_mae_mean']:.4f} & {row['random_seed_std']:.4f} \\\\"
        )
    tex_lines.extend(["\\bottomrule", "\\end{tabular}"])
    results_tex = output / "hea_sro_results.tex"
    results_tex.write_text("\n".join(tex_lines) + "\n", encoding="utf-8")

    pairs = pd.read_parquet(calibrated_pairs_path)
    required = {"xrd_l1_distance", "noise_l1_floor", "identifiability_ratio", "noise_identifiable"}
    missing = required.difference(pairs.columns)
    if missing:
        raise ValueError(f"calibrated occupancy pairs missing columns: {sorted(missing)}")
    figure, axes = plt.subplots(1, 2, figsize=(11, 4.5), constrained_layout=True)
    axes[0].scatter(
        pairs["noise_l1_floor"], pairs["xrd_l1_distance"],
        c=np.where(pairs["noise_identifiable"], "#047857", "#9CA3AF"),
        alpha=0.55, s=14,
    )
    maximum = float(max(pairs["noise_l1_floor"].max(), pairs["xrd_l1_distance"].max()))
    axes[0].plot([0, maximum], [0, maximum], color="#B91C1C", linestyle="--", label="ratio = 1")
    axes[0].set_xlabel("Parent simulated-noise L1 q95")
    axes[0].set_ylabel("Occupancy-pair L1 signal")
    axes[0].legend(frameon=False)
    axes[1].hist(pairs["identifiability_ratio"], bins=40, color="#2563EB", alpha=0.8)
    axes[1].axvline(1.0, color="#B91C1C", linestyle="--")
    axes[1].set_xlabel("Identifiability ratio")
    axes[1].set_ylabel("Pair count")
    figure.suptitle("HEA occupancy identifiability under simulated perturbations")
    occupancy_figure = output / "hea_occupancy_signal_noise.png"
    figure.savefig(occupancy_figure, dpi=220, facecolor="white")
    plt.close(figure)

    curve_rows = []
    for path in sorted(perturbation_root.rglob("perturbation_summary.json")):
        report = json.loads(path.read_text(encoding="utf-8"))
        if report.get("status") != "pass":
            continue
        for point in report.get("severity_curve", []):
            curve_rows.append({
                "model": report["model"],
                "seed": int(report["seed"]),
                "severity": (float(point["severity_min"]) + float(point["severity_max"])) / 2.0,
                "parent_macro_mae": float(point["parent_macro_mae"]),
            })
    curves = pd.DataFrame(curve_rows)
    figure, axis = plt.subplots(figsize=(7.5, 4.8), constrained_layout=True)
    if not curves.empty:
        grouped = curves.groupby(["model", "severity"])["parent_macro_mae"].agg(["mean", "std"]).reset_index()
        for model, model_rows in grouped.groupby("model"):
            axis.plot(model_rows["severity"], model_rows["mean"], marker="o", label=MODEL_LABEL.get(model, model))
            error = model_rows["std"].fillna(0.0)
            axis.fill_between(model_rows["severity"], model_rows["mean"] - error, model_rows["mean"] + error, alpha=0.15)
    axis.set_xlabel("Normalized simulated perturbation severity")
    axis.set_ylabel("Parent-macro MAE")
    axis.set_title("Matched perturbation stress test")
    axis.grid(alpha=0.2)
    axis.legend(frameon=False)
    perturbation_figure = output / "hea_perturbation_severity.png"
    figure.savefig(perturbation_figure, dpi=220, facecolor="white")
    plt.close(figure)

    artifacts = [results_csv, results_tex, occupancy_figure, perturbation_figure]
    manifest_path = output / "paper_artifacts.json"
    manifest_path.write_text(json.dumps({
        "schema_version": "sitexrd-hea-paper-artifacts-v1.1",
        "sources": [str(summary_path.resolve()), str(calibrated_pairs_path.resolve()), str(perturbation_root.resolve())],
        "artifacts": [{"path": str(path.resolve()), "sha256": _sha256(path)} for path in artifacts],
    }, indent=2, sort_keys=True), encoding="utf-8")
    return {
        "results_csv": str(results_csv.resolve()),
        "results_tex": str(results_tex.resolve()),
        "occupancy_figure": str(occupancy_figure.resolve()),
        "perturbation_figure": str(perturbation_figure.resolve()),
        "manifest": str(manifest_path.resolve()),
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--calibrated-pairs", type=Path, required=True)
    parser.add_argument("--perturbation-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    result = generate_paper_artifacts(
        args.summary.resolve(), args.calibrated_pairs.resolve(),
        args.perturbation_root.resolve(), args.output.resolve(),
    )
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
