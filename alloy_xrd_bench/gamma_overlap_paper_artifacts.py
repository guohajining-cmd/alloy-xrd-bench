"""Generate Gamma-Decomp paper artifacts from frozen evaluator outputs."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Sequence

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


MODEL_SPECS = (
    ("no-spectrum", "No-spectrum prior", False),
    ("peak-feature", "Peak Feature", True),
    ("bic", "Pseudo-Voigt (BIC)", False),
    ("resnet-set", "ResNet Set", True),
    ("transformer-set", "Transformer Set", True),
    ("physics-constrained", "Physics-constrained", True),
)
TASKS = ("full", "window")
SEEDS = (2027, 2028, 2029)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _score_dir(run_root: Path, model: str, task: str, seed: int | None) -> Path:
    if model == "no-spectrum":
        return run_root / model / task / "test" / "score"
    if model == "bic":
        return run_root / model / task / "test" / "score"
    if model == "peak-feature":
        return run_root / model / task / str(seed) / "test" / "score"
    return run_root / model / task / str(seed) / "test_score"


def _collect_scores(run_root: Path) -> tuple[pd.DataFrame, list[str]]:
    rows: list[dict[str, Any]] = []
    missing: list[str] = []
    for model, label, seeded in MODEL_SPECS:
        for task in TASKS:
            if model == "bic" and task != "window":
                continue
            seeds: tuple[int | None, ...] = SEEDS if seeded else (None,)
            for seed in seeds:
                score_dir = _score_dir(run_root, model, task, seed)
                scorecard_path = score_dir / "scorecard.json"
                if not scorecard_path.exists():
                    missing.append(str(scorecard_path))
                    continue
                scorecard = json.loads(scorecard_path.read_text(encoding="utf-8"))
                rows.append({
                    "model": model,
                    "model_label": label,
                    "task": task,
                    "seed": seed,
                    **{key: float(value) for key, value in scorecard["metrics"].items() if value is not None},
                    "score_dir": str(score_dir),
                })
    return pd.DataFrame(rows), missing


def _write_results_table(scores: pd.DataFrame, output: Path) -> tuple[Path, Path]:
    metric_columns = [
        "component_f1", "phase_hkl_accuracy", "count_accuracy",
        "center_mae_deg", "fwhm_mae_deg", "area_mae",
    ]
    aggregate = (
        scores.groupby(["task", "model", "model_label"], sort=False)[metric_columns]
        .agg(["mean", "std", "count"])
        .reset_index()
    )
    aggregate.columns = [
        "_".join(part for part in column if part).rstrip("_")
        if isinstance(column, tuple) else column
        for column in aggregate.columns
    ]
    results_csv = output / "gamma_decomp_results.csv"
    aggregate.to_csv(results_csv, index=False)
    lines = [
        "% Generated by alloy_xrd_bench.gamma_overlap_paper_artifacts; do not edit.",
        "\\begin{tabular}{llrrrrrr}",
        "\\toprule",
        "View & Model & Comp. F1 $\\uparrow$ & HKL Acc. $\\uparrow$ & Count Acc. $\\uparrow$ & "
        "Center MAE $\\downarrow$ & FWHM MAE $\\downarrow$ & Area MAE $\\downarrow$ \\\\",
        "\\midrule",
    ]
    for row in aggregate.to_dict(orient="records"):
        def formatted(metric: str) -> str:
            mean = float(row[f"{metric}_mean"])
            count = int(row[f"{metric}_count"])
            std = float(row[f"{metric}_std"]) if count > 1 else 0.0
            return f"{mean:.3f} $\\pm$ {std:.3f}" if count > 1 else f"{mean:.3f}"

        lines.append(
            f"{str(row['task']).title()} & {row['model_label']} & "
            f"{formatted('component_f1')} & {formatted('phase_hkl_accuracy')} & "
            f"{formatted('count_accuracy')} & {formatted('center_mae_deg')} & "
            f"{formatted('fwhm_mae_deg')} & {formatted('area_mae')} \\\\" 
        )
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    results_tex = output / "gamma_decomp_results.tex"
    results_tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return results_csv, results_tex


def _collect_slice_rows(scores: pd.DataFrame, filename: str, slice_column: str) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for score in scores.to_dict(orient="records"):
        path = Path(str(score["score_dir"])) / filename
        if not path.exists():
            continue
        frame = pd.read_parquet(path)
        if slice_column not in frame or "component_f1" not in frame:
            continue
        for item in frame.to_dict(orient="records"):
            rows.append({
                "task": score["task"],
                "model": score["model"],
                "model_label": score["model_label"],
                "seed": score["seed"],
                slice_column: str(item[slice_column]),
                "component_f1": float(item["component_f1"]),
            })
    return pd.DataFrame(rows)


def _write_slice_figure(
    rows: pd.DataFrame,
    slice_column: str,
    title: str,
    output_path: Path,
) -> None:
    figure, axis = plt.subplots(figsize=(8.2, 4.8), constrained_layout=True)
    if not rows.empty:
        grouped = (
            rows.groupby(["model_label", slice_column], sort=False)["component_f1"]
            .mean()
            .unstack(fill_value=np.nan)
        )
        grouped.plot(kind="bar", ax=axis, width=0.78)
    axis.set_ylim(0.0, 1.0)
    axis.set_ylabel("Component F1")
    axis.set_xlabel("")
    axis.set_title(title)
    axis.tick_params(axis="x", rotation=22)
    axis.grid(axis="y", alpha=0.2)
    if axis.get_legend() is not None:
        axis.legend(title=slice_column.replace("_", " "), frameon=False)
    figure.savefig(output_path, dpi=220, facecolor="white")
    plt.close(figure)


def generate_gamma_paper_artifacts(
    run_root: str | Path,
    output_dir: str | Path,
    *,
    require_complete: bool = False,
) -> dict[str, Any]:
    run = Path(run_root).resolve()
    output = Path(output_dir).resolve()
    output.mkdir(parents=True, exist_ok=True)
    scores, missing = _collect_scores(run)
    if scores.empty:
        raise ValueError("no frozen Gamma-Decomp scorecards found")
    if require_complete and missing:
        raise ValueError(f"Gamma-Decomp experiment matrix is incomplete: {len(missing)} scorecards missing")
    results_csv, results_tex = _write_results_table(scores, output)
    instrument_rows = _collect_slice_rows(scores, "per_instrument_slice.parquet", "instrument_slice")
    overlap_rows = _collect_slice_rows(
        scores.loc[scores["task"].eq("window")], "per_difficulty.parquet", "difficulty"
    )
    instrument_figure = output / "gamma_instrument_slices.png"
    overlap_figure = output / "gamma_overlap_difficulty.png"
    _write_slice_figure(
        instrument_rows, "instrument_slice", "Gamma-Decomp instrument shift", instrument_figure
    )
    _write_slice_figure(
        overlap_rows, "difficulty", "Gamma-Decomp overlap difficulty", overlap_figure
    )
    artifacts = [results_csv, results_tex, instrument_figure, overlap_figure]
    manifest = output / "gamma_paper_artifacts.json"
    manifest.write_text(json.dumps({
        "schema_version": "gamma-decomp-paper-artifacts-v1.1",
        "source_run_root": str(run),
        "complete_experiment_matrix": not missing,
        "missing_scorecards": missing,
        "artifacts": [
            {"path": str(path), "sha256": _sha256(path)} for path in artifacts
        ],
    }, indent=2, sort_keys=True), encoding="utf-8")
    return {
        "results_csv": str(results_csv),
        "results_tex": str(results_tex),
        "instrument_figure": str(instrument_figure),
        "overlap_figure": str(overlap_figure),
        "manifest": str(manifest),
        "complete_experiment_matrix": not missing,
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--require-complete", action="store_true")
    args = parser.parse_args(argv)
    result = generate_gamma_paper_artifacts(
        args.run_root, args.output, require_complete=args.require_complete
    )
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
